package main

import "testing"

// 缺陷P (20260913): 多段纯数字减号串 (电话/CAS/编号/日期) 被当连减算出错值。
func TestNSWDefectP_MultiSegNumberStrings(t *testing.T) {
	// 编号串: 一律不得产出锚点
	fp := []string{
		"电话 138-1234-5678", "手机 186-1234-5678", "座机 010-12345678",
		"CAS 号 50-78-2", "CAS 64-17-5", "订单 100-200-300",
		"身份证 110101-19900101-1234", "时间 14-30-45",
		"1-2-3 步骤", "第一步 1-2-3", "第 1-2-3 节",
		"1-2-3-4-5", "100-200-300-400", "纬度 39-54-27", "坐标 116-23-29",
		"时长 1-30-45", "1000-2000-3000", "5-10-15", "12-34-56",
		"9-13-2026", "9999-9999-9999", "12345-12345-12345",
	}
	for _, s := range fp {
		if a := nswEvaluate(s); len(a) != 0 {
			t.Errorf("编号串误算: %q -> %+v", s, a)
		}
	}
	// 直接判定: 多段串必须不是候选
	for _, s := range []string{"1-2-3", "10-4-3", "138-1234-5678", "1.5-2.5-3.5",
		"1 - 2 - 3", "1-2-3-4-5-6"} {
		if nswIsCandidate(s) {
			t.Errorf("nswIsCandidate 未拒绝多段减号串: %q", s)
		}
	}
	// 真算式形态必须保留 (前导负号 / 括号 / 加号串 / 乘号串 / 两段降序小数 / 幂)
	keep := map[string]string{
		"-1-2-3": "-6", "(-1)-2-3": "-6", "1+2+3": "6", "1*2*3": "6",
		"18.9-12.5": "6.4", "100-99.5": "0.5", "2^3^2": "512", "1-2+3": "2",
		"1+2-3": "0",
	}
	for e, want := range keep {
		v, ok := nswEval(e)
		if !ok || v != want {
			t.Errorf("真算式被误伤: %q -> ok=%v v=%q want=%q", e, ok, v, want)
		}
	}
}
