package main

import (
	"fmt"
	"strings"
)

// 重启脚本生成 (跨平台纯函数, T22 第 2 层)。
//
// 两平台各有原生形态: Windows 用 PowerShell(隐藏窗口 + 进程轮询 + Move-Item),
// Linux 用 sh(kill -0 轮询 + mv + nohup)。语义逐条对齐 —— 排空等待 → 超时强杀 →
// 备份失败拒绝替换 → 冒烟失败回滚 → 重建防御基线 → 拉起新进程。
//
// 二者都是纯函数(无 IO、无平台 API), 因此都能在任意平台被测试: 本机(Windows)
// 也能断言 sh 脚本的契约, 否则 Linux 侧的重启语义将完全没有判据(本机无 WSL)。
//
// 模板用 @@占位@@ 而非 fmt.Sprintf: sh 脚本里 date '+%Y-%m-%d' 的 % 与 Sprintf
// 冲突, 逐处转义 %% 易漏(漏了不报错, 静默变成 %!Y(MISSING))。

const (
	restartPlaceholderWD  = "@@WD@@"
	restartPlaceholderPID = "@@PID@@"
	restartPlaceholderTS  = "@@TS@@"
	restartPlaceholderEXE = "@@EXE@@"
)

// renderRestartTemplate 填充模板占位符 (两平台共用, 防占位符拼写漂移)。
func renderRestartTemplate(tpl, workDir string, pid int, ts string) string {
	out := strings.ReplaceAll(tpl, restartPlaceholderWD, workDir)
	out = strings.ReplaceAll(out, restartPlaceholderEXE, mainExeName())
	out = strings.ReplaceAll(out, restartPlaceholderPID, fmt.Sprintf("%d", pid))
	out = strings.ReplaceAll(out, restartPlaceholderTS, ts)
	return out
}

// restartScriptSH 是 Linux 侧重启脚本模板。
//
// 与 PowerShell 版的语义对照:
//   - 排空等待 30s      ↔ while kill -0 + deadline
//   - 超时强杀          ↔ kill -9
//   - 备份失败拒绝替换  ↔ cp || { ...; exit 1; }
//   - 冒烟失败回滚      ↔ "$exe" --version 判 exit code 与输出非空
//   - 重建防御基线      ↔ python3 优先/回落 python 跑 forge_guard.py init
//   - 隐藏窗口拉起新进程 ↔ nohup ... & (脱离终端)
//
// 正文保持纯 ASCII: 与 PowerShell 版同理 —— 终端 locale 不确定时中文日志会乱码。
const restartScriptSH = `#!/bin/sh
# auto-generated by /upgrade - do not edit
wd='@@WD@@'
exe='@@EXE@@'
log="$wd/.forge/upgrade_restart.log"
log_msg() { echo "$(date '+%Y-%m-%dT%H:%M:%S') $1" >> "$log"; }
log_msg "=== restart begin (pid @@PID@@) ==="
cd "$wd" || { log_msg "FATAL: cd $wd failed"; exit 1; }
# drain wait: main process exits by itself (defer saves cache), 30s cap
deadline=$(( $(date +%s) + 30 ))
while kill -0 @@PID@@ 2>/dev/null && [ "$(date +%s)" -lt "$deadline" ]; do
    sleep 1
done
# timeout only then force kill (fallback)
if kill -0 @@PID@@ 2>/dev/null; then
    log_msg "drain timeout, force kill pid @@PID@@"
    kill -9 @@PID@@
    sleep 1
fi
# backup BEFORE replace: no backup = no rollback, so refuse to touch the binary
cp "$exe" "$exe.bak_@@TS@@" || { log_msg "FATAL: backup failed, refuse to replace (old binary intact)"; exit 1; }
mv "$exe.new" "$exe" || { log_msg "FATAL: deploy failed, $exe unchanged"; exit 1; }
# smoke test: compiled != runnable. roll back if the new binary cannot report its version
smoke=$("$exe" --version 2>&1)
code=$?
if [ "$code" -ne 0 ] || [ -z "$(printf '%s' "$smoke" | tr -d '[:space:]')" ]; then
    log_msg "FATAL: smoke test failed (exit=$code), rolling back"
    mv "$exe" "$exe.new.failed_@@TS@@"
    mv "$exe.bak_@@TS@@" "$exe"
    if [ ! -x "$exe" ]; then log_msg "FATAL: rollback failed, backup kept at $exe.bak_@@TS@@"; exit 1; fi
    log_msg "rolled back to previous binary"
    nohup "$exe" >> "$log" 2>&1 &
    exit 1
fi
log_msg "smoke test ok: $smoke"
PY=python3
command -v python3 >/dev/null 2>&1 || PY=python
"$PY" defense_system/forge_guard.py init >> "$log" 2>&1
nohup "$exe" >> "$log" 2>&1 &
log_msg "=== restart ok ==="
`

// buildRestartScriptSH 生成 Linux 侧排空式重启脚本内容 (纯函数, 可测试)。
func buildRestartScriptSH(workDir string, pid int, ts string) string {
	return renderRestartTemplate(restartScriptSH, workDir, pid, ts)
}
