package main

// ── 程序注入消息的统一来源信封 (缺陷P, 20260912) ─────────────────────────────
//
// 现象: 无剑反馈与虚报干预都以 Role:"user" 塞进当轮 messages, 对模型而言与主人的
// 真实输入形式上完全同形 —— 都是裸 user 消息, 零来源标记。实测后果: 模型把死程序
// 塞进去的求值反馈当成"用户发来的内容", 连续三轮报告建立在错误前提上(还据此提出
// 了针对该幻象的"修复方案"), 而用户当轮真正的指令被劫持。
//
// 对照: 用户每次输入都被包装成 <recalled_memory>...</recalled_memory> + 原话, 有
// 明确来源标签; 注入消息此前一个标签都没有 —— 模型分不清谁是主人。这是"注意力"
// 层面的缺陷, 不是内容层面的 (公理一: 注意力是稀缺资源)。
//
// 修法: 统一信封前缀。仍走 user 角色 (保证模型必然看到), 只加文本不改协议。
//
// 为什么不用 role:"system":
//   - OpenAI 兼容端点多条 system 可能被合并或丢弃, 注入会静默失效;
//   - 历史中插 system 会破坏前缀缓存 (见缓存铁律 98%->57-69% 教训)。
//
// 为什么信封里不含动态内容:
//
//	信封是常量串 (kind + 固定说明), 且注入消息本就不入 a.history, 故对前缀缓存零影响。
//
// 为什么改在构造侧而非渲染侧 (ux.go):
//
//	注入消息从不上屏 (只进当轮 messages, 不进 history/checkpoint), 需要被纠正的是
//	"模型读到的来源", 故必须在构造注入文本处加, 改渲染层无效。
//
// 自我克制: 信封自身不含任何算式候选, 不会被无剑嗅探回环 (与 J6 同向)。
// 边界: 历史同步类消息 (【记忆已更新】/【待办更新】/【档案索引已更新】) 语义自明且
// 用户不可见, 不纳入本次信封范围。
func autoInjectEnvelope(kind, body string) string {
	return "〔铸剑炉自动注入·非用户消息〕" + kind +
		"：以下内容由确定性死程序生成，不是用户发言，也不是用户对你的要求。" +
		"请把它当作工具返回的客观事实处理：\n" + body
}
