package main

import "testing"

// 缺陷U (20261015): 两类自然语言形态绕过锚定正则被误求值 —— 基线用真实 nswEvaluate 实测复现:
//
//	U1 混合分隔符多段列举 "8-12/13/18/22/24/26/28" -> 7.99999986659 (日期·班次列举)
//	U2 Markdown 列表前导  "- 10-14"              -> -24         (列表项被当连减)
//
// 根因同族: 全部区间/日期闸锚定 ^\d, 复合形态与列表前导各从一侧绕过。
// 本用例是这两条闸的回归红线 —— 既钉住"必须拒", 也钉住"真算式不得被误伤"。
func TestNSWDefectU_ListPrefixAndMixedSeparator(t *testing.T) {
	// U1+U2 实测形态及其同族: 一律不得产出锚点
	reject := []string{
		"排班 8-12/13/18/22/24/26/28 全天",
		"- 10-14 全天",
		"- 12-15 门诊",
		"- 2026-09-10 记录",
		"值班 9-09/10/12/28 各日",
		"窗口 10-01/03/04/08/13 开放",
	}
	for _, s := range reject {
		if a := nswEvaluate(s); len(a) != 0 {
			t.Errorf("列举/列表形态误算: %q -> %+v", s, a)
		}
	}
	// 直接判定 (不经位置上下文): 候选闸本身必须拒绝
	for _, s := range []string{"8-12/13/18/22/24/26/28", "- 10-14", "+ 10-14", "- 2026-09-10"} {
		if nswIsCandidate(s) {
			t.Errorf("nswIsCandidate 未拒绝列举/列表形态: %q", s)
		}
	}
	// 真算式形态必须保留 (与缺陷P keep 集合同口径, 防剥离闸与泛化闸误伤)
	keep := map[string]string{
		"-1-2-3": "-6", "(-1)-2-3": "-6", "18.9-12.5": "6.4",
		"12-5/2": "9.5", "1-2/3": "0.333333333333", "3/4-1/2": "0.25",
	}
	for e, want := range keep {
		v, ok := nswEval(e)
		if !ok || v != want {
			t.Errorf("真算式被误伤: %q -> ok=%v v=%q want=%q", e, ok, v, want)
		}
	}
	// 区间闸只在嗅探口径生效: 显式 {{10-14}} 是意图声明, 照旧求值 (剥离闸同口径, 只增拒不求值)
	if !nswIsCandidateMode("10-14", true) {
		t.Error("显式口径下 10-14 应仍是候选 (区间闸仅嗅探生效)")
	}
}
